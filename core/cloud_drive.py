"""
Cloud Drive Integration Module - Aayushifty CloudDesk 2.0
Central Cloud-First Storage Engine.
Manages Google Drive for Desktop in Stream Files mode as the primary storage layer,
retrieves actual dynamic storage quotas, and provides detailed analytics across all cloud categories.
"""
from __future__ import annotations

import os
import psutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

REQUIRED_CLOUD_FOLDERS = [
    "Projects",
    "AI_Models",
    "Datasets",
    "Development_Assets",
    "Videos",
    "PCB_Designs",
    "Archives",
    "Backups",
    "Documentation"
]

FOLDER_DESCRIPTIONS = {
    "Projects": "Central development project folders. Source code and heavy project assets.",
    "AI_Models": "Central repository for AI model weights (GGUF, safetensors, checkpoints).",
    "Datasets": "Central store for AI training datasets (CSV, Parquet, images, audio).",
    "Development_Assets": "Shared textures, 3D assets, Figma exports, and media files.",
    "Videos": "Raw video captures, screen recordings, B-roll, and final renders.",
    "PCB_Designs": "KiCad, Gerber, schematics, and hardware engineering files.",
    "Archives": "Verified project completion archives and legacy code snapshots.",
    "Backups": "Automated clean project backup archives generated by CloudDesk.",
    "Documentation": "Architecture documents, project manuals, and API specifications."
}


class CloudDriveManager:
    """Manages Google Drive for Desktop integration, folder structure, and storage analytics."""

    @staticmethod
    def is_drive_installed() -> bool:
        """Checks if Google Drive for Desktop executable exists on the system."""
        common_paths = [
            Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Google" / "Drive File Stream",
            Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Google" / "Drive File Stream"
        ]
        for p in common_paths:
            if p.exists() and any(p.glob("**/GoogleDriveFS.exe")):
                return True
        return False

    @staticmethod
    def is_drive_running() -> bool:
        """Checks if GoogleDriveFS process is currently active."""
        for p in psutil.process_iter(['name']):
            try:
                name = p.info.get('name') or ''
                if "googledrivefs" in name.lower():
                    return True
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                continue
        return False

    @classmethod
    def get_drive_mount(cls) -> Optional[Path]:
        """Detects the virtual drive mount for Google Drive (usually G:, H:, etc.)."""
        # First check G:\ (standard default)
        standard_g = Path("G:/")
        if standard_g.exists():
            return standard_g

        # Otherwise check all mounted drives
        for p in psutil.disk_partitions(all=False):
            mount = p.mountpoint
            try:
                if "google" in p.device.lower() or "google drive" in p.opts.lower():
                    return Path(mount)
                if (Path(mount) / "My Drive").exists():
                    return Path(mount)
            except Exception:
                continue

        return None

    @classmethod
    def get_my_drive_path(cls) -> Optional[Path]:
        """Returns the absolute path to the user's 'My Drive' cloud folder."""
        mount = cls.get_drive_mount()
        if not mount:
            return None

        my_drive = mount / "My Drive"
        if my_drive.exists():
            return my_drive

        return mount

    @classmethod
    def get_status(cls) -> Dict[str, Any]:
        """Returns Google Drive running status, mount point, and folders."""
        installed = cls.is_drive_installed()
        running = cls.is_drive_running()
        mount = cls.get_drive_mount()
        my_drive = cls.get_my_drive_path()

        folders_status = {}
        if my_drive and my_drive.exists():
            for folder in REQUIRED_CLOUD_FOLDERS:
                target = my_drive / folder
                folders_status[folder] = target.exists()

        quota_info = None
        if mount and mount.exists():
            try:
                usage = psutil.disk_usage(str(mount))
                quota_info = {
                    "total_gb": round(usage.total / (1024 ** 3), 2),
                    "total_tb": round(usage.total / (1024 ** 4), 2),
                    "used_gb": round(usage.used / (1024 ** 3), 2),
                    "used_tb": round(usage.used / (1024 ** 4), 2),
                    "free_gb": round(usage.free / (1024 ** 3), 2),
                    "free_tb": round(usage.free / (1024 ** 4), 2),
                    "percent": usage.percent
                }
            except Exception:
                pass

        return {
            "installed": installed,
            "running": running,
            "mount_point": str(mount) if mount else None,
            "my_drive_path": str(my_drive) if my_drive else None,
            "stream_mode_active": mount is not None,
            "folders_initialized": all(folders_status.values()) if folders_status else False,
            "folders": folders_status,
            "quota": quota_info
        }

    @classmethod
    def initialize_folder_structure(cls) -> Tuple[bool, str, List[str]]:
        """Creates the 9 cloud workspace directories with documentation."""
        my_drive = cls.get_my_drive_path()
        if not my_drive:
            return False, "Google Drive is not mounted. Please ensure Google Drive is running.", []

        created = []
        for folder in REQUIRED_CLOUD_FOLDERS:
            folder_path = my_drive / folder
            try:
                folder_path.mkdir(parents=True, exist_ok=True)
                readme_path = folder_path / "_CLOUDDESK_README.txt"
                if not readme_path.exists():
                    desc = FOLDER_DESCRIPTIONS.get(folder, "CloudDesk unified directory.")
                    content = (
                        f"=== Aayushifty CloudDesk 2.0: {folder} ===\n\n"
                        f"Purpose: {desc}\n\n"
                        f"Cloud-First Storage Architecture:\n"
                        f"- Primary central storage location on Google Drive (Stream Files Mode).\n"
                        f"- Does not consume local C: SSD space.\n"
                        f"- Connects to Google Colab via: /content/drive/MyDrive/{folder}\n"
                        f"- WARNING: Do NOT place active node_modules, .venv, or SQLite databases here.\n"
                    )
                    readme_path.write_text(content, encoding="utf-8")
                created.append(str(folder_path))
            except Exception as e:
                return False, f"Failed creating {folder}: {str(e)}", created

        return True, "Cloud workspace structure initialized successfully.", created

    @classmethod
    def get_cloud_storage_analytics(cls) -> Dict[str, Any]:
        """
        Retrieves real-time actual quota and calculates category consumption
        across Projects, Datasets, AI_Models, Backups, and Archives.
        """
        my_drive = cls.get_my_drive_path()
        status = cls.get_status()
        quota = status.get("quota")

        category_breakdown = {}
        total_category_bytes = 0

        if my_drive and my_drive.exists():
            for folder in REQUIRED_CLOUD_FOLDERS:
                folder_path = my_drive / folder
                cat_bytes = 0
                cat_files = 0
                if folder_path.exists():
                    try:
                        for f in folder_path.rglob("*"):
                            if f.is_file():
                                cat_bytes += f.stat().st_size
                                cat_files += 1
                    except Exception:
                        pass
                category_breakdown[folder] = {
                    "size_mb": round(cat_bytes / (1024 ** 2), 2),
                    "size_gb": round(cat_bytes / (1024 ** 3), 3),
                    "files_count": cat_files
                }
                total_category_bytes += cat_bytes
        else:
            for folder in REQUIRED_CLOUD_FOLDERS:
                category_breakdown[folder] = {"size_mb": 0.0, "size_gb": 0.0, "files_count": 0}

